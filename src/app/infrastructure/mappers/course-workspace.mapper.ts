import { CourseResource, CourseWorkspace } from '../../domain/models/course-workspace.model';
import { PanelCursoDto } from '../dtos/course-workspace.dto';

export function mapCourseWorkspace(dto: PanelCursoDto): CourseWorkspace {
  const c = dto.curso;
  return {
    canManage: dto.puedeGestionar === true,
    completedResourceIds: dto.contenidosCompletados ?? [],
    stats: dto.estadisticas
      ? {
          totalStudents: dto.estadisticas.totalAlumnos,
          activeStudents: dto.estadisticas.alumnosActivos,
          averageProgress: dto.estadisticas.progresoPromedio,
          publishedResources: dto.estadisticas.recursosPublicados,
        }
      : undefined,
    course: {
      id: c.id,
      title: c.titulo,
      description: c.descripcion ?? '',
      level: c.nivelCefr,
      status: c.estado,
      teacherId: c.docente.id,
      teacherName: `${c.docente.nombre} ${c.docente.apellido}`.trim(),
      schedule: c.horario,
      startsOn: c.fechaInicio,
      endsOn: c.fechaFin,
      capacity: c.capacidadMaxima,
    },
    units: dto.unidades.map(({ unidad: u, semanas }) => ({
      id: u.id,
      number: u.numero,
      title: u.titulo,
      description: u.descripcion ?? '',
      weeks: semanas.map(({ semana: s, clases, materiales, tareas }) => ({
        id: s.id,
        unitId: s.unidadId,
        number: s.numero,
        title: s.titulo,
        description: s.descripcion ?? '',
        isCurrent: s.esActual,
        resources: [
          ...clases.map((r): CourseResource => ({
            id: r.id,
            weekId: s.id,
            kind: 'CLASS',
            published: r.publicado === true,
            visible: r.visible === true,
            title: r.titulo,
            description: r.descripcion ?? '',
            externalUrl: r.urlVivo,
            recordingUrl: r.urlGrabacion,
            startsAt: r.fechaHora,
            durationMinutes: r.duracionMinutos,
            room: r.sala,
          })),
          ...materiales.map((r): CourseResource => ({
            id: r.id,
            weekId: s.id,
            kind: 'MATERIAL',
            published: r.publicado === true,
            visible: r.visible === true,
            title: r.titulo,
            description: r.descripcion ?? '',
            materialType: r.tipo,
            sizeMb: r.tamanoMb,
            fileUrl: r.urlArchivo,
            externalUrl: r.urlExterno,
          })),
          ...tareas.map((r): CourseResource => ({
            id: r.id,
            weekId: s.id,
            kind: 'TASK',
            published: r.publicado === true,
            visible: r.visible === true,
            activityType: r.tipoActividad ?? 'TAREA',
            title: r.titulo,
            description: r.descripcion ?? '',
            externalUrl: r.instruccionesUrl,
            dueAt: r.fechaLimite,
            maxScore: r.puntajeMaximo,
          })),
        ],
      })),
    })),
    students: dto.matriculas.map((m) => ({
      enrollmentId: m.id,
      id: m.estudianteId,
      name: m.estudianteNombreCompleto,
      email: m.estudianteCorreo,
      status: m.estado,
      grade: m.notaFinal,
      attendance: m.asistenciaPorcentaje,
      enrolledAt: m.matriculadoAt,
      avatarUrl: dto.avances?.find((a) => a.estudianteId === m.estudianteId)?.avatarUrl ?? null,
      progress: dto.avances?.find((a) => a.estudianteId === m.estudianteId)?.progreso ?? null,
    })),
    announcements: dto.anuncios.map((a) => ({
      imageUrl: a.imagenUrl ?? null,
      id: a.id,
      title: a.titulo,
      body: a.cuerpo,
      author: a.autorNombreCompleto,
      active: a.activo,
      createdAt: a.fechaCreacion,
      published: a.publicado === true,
      pinned: a.fijado === true,
      publishedAt: a.publicadoAt ?? null,
    })),
    submissions: dto.entregas.map((e) => ({
      id: e.id,
      taskId: e.tareaId,
      taskTitle: e.tareaTitulo,
      studentId: e.estudianteId,
      studentName: e.estudianteNombreCompleto,
      fileUrl: e.urlArchivo,
      submittedAt: e.enviadoAt,
      grade: e.nota,
      feedback: e.retroalimentacion,
      status: e.estado,
      textContent: e.textoRespuesta ?? null,
      isLate: e.tardia === true,
      gradedAt: e.calificadoAt ?? null,
      graderName: e.calificadoPorNombreCompleto ?? null,
    })),
  };
}
