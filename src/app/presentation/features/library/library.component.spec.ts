import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { TestBed } from '@angular/core/testing';
import { computed, signal } from '@angular/core';
import { environment } from '../../../core/config/environment';
import { TokenStorageService } from '../../../core/services/token-storage.service';
import { UserProfile } from '../../../domain/models/user.model';
import { LibraryComponent } from './library.component';

describe('Biblioteca', () => {
  const base = `${environment.apiUrl}/api/recursos`;
  const recurso = { id: 'resource', titulo: 'Guía', categoria: 'Lectura', nivelCefr: 'A1', tipo: 'PDF', contadorDescargas: 0 };
  let http: HttpTestingController;
  let currentUser: ReturnType<typeof signal<UserProfile | null>>;
  beforeEach(() => {
    currentUser = signal<UserProfile | null>(null);
    const isAdmin = computed(() => currentUser()?.role === 'ADMINISTRADOR' || !!currentUser()?.roles?.includes('ADMINISTRADOR'));
    TestBed.configureTestingModule({ imports: [LibraryComponent], providers: [provideHttpClient(), provideHttpClientTesting(), { provide: TokenStorageService, useValue: { currentUser, isAdmin } }] });
    http = TestBed.inject(HttpTestingController);
  });
  afterEach(() => http.verify());
  it('filtra el catálogo y registra la descarga antes de ofrecer el recurso', () => {
    const fixture = TestBed.createComponent(LibraryComponent);
    fixture.detectChanges();
    const initial = http.expectOne((request) => request.url === base);
    expect(initial.request.params.get('size')).toBe('20');
    initial.flush({ content: [recurso], number: 0, totalPages: 1, totalElements: 1 });
    fixture.componentInstance.search = 'Guía';
    fixture.componentInstance.level = 'A1';
    fixture.componentInstance.load(0);
    const filtered = http.expectOne((request) => request.url === base);
    expect(filtered.request.params.get('titulo')).toBe('Guía');
    expect(filtered.request.params.get('nivelCefr')).toBe('A1');
    filtered.flush({ content: [recurso], number: 0, totalPages: 1, totalElements: 1 });
    fixture.componentInstance.download(recurso);
    const download = http.expectOne(`${base}/resource/descargar`);
    expect(download.request.method).toBe('POST');
    download.flush({ urlArchivo: 'https://files.example/guia.pdf', urlExterno: null, contadorDescargas: 1 });
    expect(fixture.componentInstance.ready()?.url).toBe('https://files.example/guia.pdf');
  });
  it('no ofrece enlaces inseguros y muestra un error si la descarga falla', () => {
    const fixture = TestBed.createComponent(LibraryComponent);
    fixture.detectChanges();
    http.expectOne((request) => request.url === base).flush({ content: [recurso], number: 0, totalPages: 1, totalElements: 1 });
    fixture.componentInstance.download(recurso);
    http.expectOne(`${base}/resource/descargar`).flush({ urlArchivo: 'javascript:alert(1)', urlExterno: null });
    expect(fixture.componentInstance.ready()).toBeNull();
    expect(fixture.componentInstance.downloadError()).toBeTruthy();
  });
  it('el estudiante puede consultar y descargar, pero no ve ni ejecuta acciones de gestión', () => {
    currentUser.set({ id: 's', email: 's@example.test', fullName: 'Estudiante', role: 'ESTUDIANTE', roles: ['ESTUDIANTE'], status: 'ACTIVO' });
    const fixture = TestBed.createComponent(LibraryComponent);
    fixture.detectChanges();
    http.expectOne((request) => request.url === base).flush({ content: [recurso], number: 0, totalPages: 1, totalElements: 1 });
    fixture.detectChanges();
    const content = fixture.nativeElement as HTMLElement;
    expect(content.textContent).toContain('Abrir recurso');
    expect(content.textContent).not.toContain('Agregar recurso');
    expect(content.textContent).not.toContain('Editar');
    expect(content.textContent).not.toContain('Eliminar');
    fixture.componentInstance.create();
    fixture.componentInstance.edit(recurso);
    fixture.componentInstance.remove(recurso);
    expect(fixture.componentInstance.editorOpen()).toBe(false);
    expect(fixture.componentInstance.confirmation()).toBeNull();
  });
  it('el docente sube un archivo y lo registra como recurso de biblioteca', () => {
    currentUser.set({ id: 'd', email: 'd@example.test', fullName: 'Docente', role: 'DOCENTE', roles: ['DOCENTE'], status: 'ACTIVO' });
    const fixture = TestBed.createComponent(LibraryComponent);
    fixture.detectChanges();
    http.expectOne((request) => request.url === base).flush({ content: [], number: 0, totalPages: 0, totalElements: 0 });
    const component = fixture.componentInstance;
    component.create();
    component.form.titulo = 'Nueva guía';
    component.selectedFile.set(new File(['contenido'], 'guia.pdf', { type: 'application/pdf' }));
    component.save();
    const upload = http.expectOne(`${environment.apiUrl}/api/biblioteca/archivos`);
    expect(upload.request.method).toBe('POST');
    expect(upload.request.body.get('archivo').name).toBe('guia.pdf');
    upload.flush({ id: 'f', nombre: 'guia.pdf', mime: 'application/pdf', bytes: 9, url: 'https://api.example.test/api/biblioteca/archivos/f' });
    const create = http.expectOne(base);
    expect(create.request.method).toBe('POST');
    expect(create.request.body.urlArchivo).toBe('https://api.example.test/api/biblioteca/archivos/f');
    create.flush({ id: 'new' });
    http.expectOne((request) => request.url === base && request.method === 'GET').flush({ content: [], number: 0, totalPages: 0, totalElements: 0 });
    expect(component.editorOpen()).toBe(false);
  });
  it('el docente puede editar metadatos sin reemplazar el archivo existente', () => {
    currentUser.set({ id: 'd', email: 'd@example.test', fullName: 'Docente', role: 'DOCENTE', roles: ['DOCENTE'], status: 'ACTIVO' });
    const fixture = TestBed.createComponent(LibraryComponent);
    fixture.detectChanges();
    http.expectOne((request) => request.url === base).flush({ content: [recurso], number: 0, totalPages: 1, totalElements: 1 });
    const component = fixture.componentInstance;
    component.edit(recurso);
    http.expectOne(`${base}/resource`).flush({ ...recurso, descripcion: 'Descripción', urlArchivo: 'https://api.example.test/api/biblioteca/archivos/f', urlExterno: null, tamanoMb: 1 });
    component.form.titulo = 'Guía actualizada';
    component.save();
    const update = http.expectOne(`${base}/resource`);
    expect(update.request.method).toBe('PUT');
    expect(update.request.body.titulo).toBe('Guía actualizada');
    expect(update.request.body.urlArchivo).toBe('https://api.example.test/api/biblioteca/archivos/f');
    update.flush({ ...recurso, titulo: 'Guía actualizada' });
    http.expectOne((request) => request.url === base && request.method === 'GET').flush({ content: [], number: 0, totalPages: 0, totalElements: 0 });
    expect(component.canDelete()).toBe(false);
  });
  it('un docente que también es administrador puede eliminar tras confirmar', () => {
    currentUser.set({ id: 'a', email: 'a@example.test', fullName: 'Admin', role: 'DOCENTE', roles: ['DOCENTE', 'ADMINISTRADOR'], status: 'ACTIVO' });
    const fixture = TestBed.createComponent(LibraryComponent);
    fixture.detectChanges();
    http.expectOne((request) => request.url === base).flush({ content: [recurso], number: 0, totalPages: 1, totalElements: 1 });
    fixture.detectChanges();
    expect((fixture.nativeElement as HTMLElement).textContent).toContain('Eliminar');
    fixture.componentInstance.remove(recurso);
    fixture.detectChanges();
    expect((fixture.nativeElement as HTMLElement).textContent).toContain('historial de descargas');
    expect((fixture.nativeElement as HTMLElement).textContent).toContain('no se elimina automáticamente');
    fixture.componentInstance.confirmDelete();
    const remove = http.expectOne(`${base}/resource`);
    expect(remove.request.method).toBe('DELETE');
    remove.flush(null);
    http.expectOne((request) => request.url === base && request.method === 'GET').flush({ content: [], number: 0, totalPages: 0, totalElements: 0 });
  });
  it('conserva el archivo subido si falla guardar los metadatos para permitir reintentar', () => {
    currentUser.set({ id: 'd', email: 'd@example.test', fullName: 'Docente', role: 'DOCENTE', status: 'ACTIVO' });
    const fixture = TestBed.createComponent(LibraryComponent);
    fixture.detectChanges();
    http.expectOne((request) => request.url === base).flush({ content: [], number: 0, totalPages: 0, totalElements: 0 });
    const component = fixture.componentInstance;
    component.create();
    component.form.titulo = 'Guía';
    component.selectedFile.set(new File(['x'], 'guia.pdf', { type: 'application/pdf' }));
    component.save();
    http.expectOne(`${environment.apiUrl}/api/biblioteca/archivos`).flush({ id: 'f', nombre: 'guia.pdf', mime: 'application/pdf', bytes: 1, url: 'https://api.example.test/api/biblioteca/archivos/f' });
    http.expectOne(base).flush({ mensaje: 'Error' }, { status: 500, statusText: 'Error' });
    expect(component.form.urlArchivo).toContain('/api/biblioteca/archivos/f');
    expect(component.selectedFile()).toBeNull();
    component.save();
    const retry = http.expectOne(base);
    expect(retry.request.body.urlArchivo).toContain('/api/biblioteca/archivos/f');
    retry.flush({ id: 'new' });
    http.expectOne((request) => request.url === base && request.method === 'GET').flush({ content: [], number: 0, totalPages: 0, totalElements: 0 });
  });
});
